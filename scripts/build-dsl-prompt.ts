import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { readDslDoc } from "@/lib/dsl/spec";

// docs/dsl.md is the source of truth for the DSL. The system prompt embeds it
// verbatim through a generated module so the prompt cannot drift from the docs
// and so the bundler does not have to read markdown at runtime.
export const GENERATED_PATH = join(process.cwd(), "lib", "ai", "dslPrompt.generated.ts");

export function renderGeneratedModule(doc: string): string {
  const escaped = doc.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");
  return [
    "// Generated by scripts/build-dsl-prompt.ts from docs/dsl.md. Do not edit.",
    "// Run `pnpm dsl:prompt` after changing the docs.",
    "",
    `export const DSL_DOC = \`${escaped}\`;`,
    "",
  ].join("\n");
}

function main(): void {
  const doc = readDslDoc();
  writeFileSync(GENERATED_PATH, renderGeneratedModule(doc), "utf8");
  process.stdout.write(`Wrote ${GENERATED_PATH}\n`);
}

if (process.argv[1] && process.argv[1].endsWith("build-dsl-prompt.ts")) {
  main();
}
